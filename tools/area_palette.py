"""Take each area's colours from its world-map art (assets/ui/areas/<i>.webp) and write them into
src/game/11-world-data.js between the // <area-art-palette> markers: ground (4 tones), fog, sky (top, horizon), minimap.
Usage: python3 tools/area_palette.py   (then node tools/build.cjs)"""
import os, re
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hx = lambda c: '0x%02x%02x%02x' % tuple(int(max(0, min(255, v))) for v in c)
def soften(c, s=0.85, v=0.92):  # a little less saturated and bright, so monsters and loot still read on the ground
    c = np.asarray(c, float); g = c.mean(); return (g + (c - g) * s) * v

def palette(path):
    a = np.asarray(Image.open(path).convert('RGB')).astype(float); h = a.shape[0]
    top = a[: int(h * .12)].reshape(-1, 3).mean(0); hor = a[int(h * .38): int(h * .48)].reshape(-1, 3).mean(0)
    low = a[int(h * .62): int(h * .92)].reshape(-1, 3); lum = low @ [.3, .59, .11]
    low = low[(lum > 30) & (lum < 235)]
    q = Image.fromarray(low[: (len(low) // 64) * 64].reshape(-1, 64, 3).astype(np.uint8)).quantize(4, method=Image.Quantize.MEDIANCUT)
    pal = np.array(q.getpalette()[:12], float).reshape(4, 3); cnt = np.bincount(np.asarray(q).ravel(), minlength=4)
    ground = [soften(pal[i]) for i in np.argsort(-cnt)]
    fog = (np.mean(ground, 0) * .5 + hor * .5)
    return {'ground': ground, 'fog': fog, 'sky': [soften(top, .9, .8), soften(hor, .9, .95)], 'mm': np.mean(ground, 0)}

rows = []
for i in range(30):
    p = palette(os.path.join(ROOT, 'assets', 'ui', 'areas', f'{i}.webp'))
    mm = '#%02x%02x%02x' % tuple(int(v) for v in p['mm'])
    rows.append(f"  {{ ground: [{', '.join(hx(c) for c in p['ground'])}], fog: {hx(p['fog'])}, sky: [{hx(p['sky'][0])}, {hx(p['sky'][1])}], mm: '{mm}' }},")
block = "// <area-art-palette> generated by tools/area_palette.py from assets/ui/areas/: each area takes the colours of its own art\nconst AREA_ART_PALETTE = [\n" + "\n".join(rows) + "\n];\nAREA_ART_PALETTE.forEach((c, i) => { if (WORLD_AREAS[i]) Object.assign(WORLD_AREAS[i], c); });\n// </area-art-palette>"
f = os.path.join(ROOT, 'src', 'game', '11-world-data.js'); s = open(f).read()
if '// <area-art-palette>' in s: s = re.sub(r"// <area-art-palette>.*?// </area-art-palette>", lambda m: block, s, flags=re.S)
else: s = s.replace("const WORLD_AREAS = buildWorldAreas();\n", "const WORLD_AREAS = buildWorldAreas();\n" + block + "\n", 1)
open(f, 'w').write(s); print('wrote', len(rows), 'area palettes')
